function soma(a, b) {
return a + b;
}

function multiplicar(a, b) {
    return a * b;
}

function quadrado(a) {
    return a ** a;
}
let resultado = soma(5, 3);
let resultadoMult = multiplicar(5,3);
let resultadoQuad = quadrado(5);
console.log("Resultado da soma:", resultado);
console.log("Resultado da multiplicação:", resultadoMult);
console.log("Resultado do quadrado:", resultadoQuad);



